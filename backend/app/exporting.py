"""Project report export (user-flow step 9) and CSV feeds for Power BI."""
from __future__ import annotations

import csv
import io
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter

HEADER_FILL = PatternFill("solid", fgColor="215D45")
HEADER_FONT = Font(color="FFFFFF", bold=True)


def _sheet(wb: Workbook, title: str, rows: list[dict[str, Any]], columns: list[tuple[str, str]]) -> None:
    ws = wb.create_sheet(title)
    ws.append([label for _, label in columns])
    for cell in ws[1]:
        cell.fill, cell.font = HEADER_FILL, HEADER_FONT
    for row in rows:
        ws.append([row.get(key) for key, _ in columns])
    for index, (key, label) in enumerate(columns, start=1):
        width = max([len(str(label))] + [len(str(r.get(key) or "")) for r in rows[:200]])
        ws.column_dimensions[get_column_letter(index)].width = min(max(width + 2, 10), 60)
    ws.freeze_panes = "A2"


def project_workbook(project: dict, summary: dict, activities: list[dict], dependency: dict, predictions: dict,
                     reports: list[dict], audit: list[dict], generated_by: str) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    ws["A1"] = f"InfraSight AI — {project['name']}"
    ws["A1"].font = Font(size=16, bold=True)
    lines = [
        ("Baseline / as of", project.get("as_of")),
        ("Generated by", generated_by),
        ("Activities", summary["activities"]),
        ("Planned progress (unweighted mean)", f"{summary['planned']}%"),
        ("Actual progress (unweighted mean)", f"{summary['actual']}%"),
        ("Activities behind plan", summary["behind"]),
        ("Critical path", " → ".join(dependency.get("critical_path", []))),
        ("Planned project finish", dependency.get("project_finish")),
        ("Delay model", predictions.get("model", {}).get("version")),
        ("Delay model ROC-AUC (synthetic hold-out)", predictions.get("model", {}).get("metrics", {}).get("roc_auc")),
        ("High-risk activities", ", ".join(p["activity_id"] for p in predictions.get("predictions", []) if p["risk_level"] == "high") or "None"),
        ("Note", predictions.get("note", "")),
    ]
    for offset, (label, value) in enumerate(lines, start=3):
        ws.cell(offset, 1, label).font = Font(bold=True)
        ws.cell(offset, 2, value).alignment = Alignment(wrap_text=True)
    ws.column_dimensions["A"].width = 42
    ws.column_dimensions["B"].width = 80

    nodes = {n["id"]: n for n in dependency.get("nodes", [])}
    act_rows = [{**a, "critical": "yes" if nodes.get(a["id"], {}).get("critical") else "",
                 "float": nodes.get(a["id"], {}).get("total_float_days"),
                 "downstream": nodes.get(a["id"], {}).get("downstream_count")} for a in activities]
    _sheet(wb, "Activities", act_rows, [("id", "Activity ID"), ("name", "Name"), ("planned", "Planned %"), ("actual", "Actual %"),
                                         ("variance", "Variance (pp)"), ("predecessor", "Predecessors"),
                                         ("planned_start", "Planned start"), ("planned_finish", "Planned finish"),
                                         ("duration_days", "Duration (d)"), ("total_quantity", "Total quantity"), ("unit", "Unit"),
                                         ("actual_quantity", "Quantity done"), ("critical", "Critical"),
                                         ("float", "Total float (d)"), ("downstream", "Downstream activities")])
    risk_rows = [{**p, "factors_text": "; ".join(f["label"] for f in p.get("factors", []))} for p in predictions.get("predictions", [])]
    _sheet(wb, "Delay risk", risk_rows, [("activity_id", "Activity ID"), ("name", "Name"), ("delay_probability", "P(delay)"),
                                         ("expected_delay_days", "Expected delay (d)"), ("risk_score", "Risk score"),
                                         ("risk_level", "Risk level"), ("downstream_count", "Downstream"),
                                         ("factors_text", "Main factors")])
    _sheet(wb, "Reports", reports, [("id", "Report"), ("activity_id", "Activity"), ("progress", "Progress %"),
                                    ("quantity_done", "Quantity"), ("quantity_unit", "Unit"),
                                    ("reporting_date", "Date"), ("status", "Status"), ("source", "Source"),
                                    ("match_status", "Match"), ("match_score", "Score"), ("model", "Model"), ("text", "Evidence")])
    _sheet(wb, "Audit trail", audit, [("id", "Entry"), ("report_id", "Report"), ("action", "Action"), ("actor", "By"),
                                      ("created_at", "When"), ("details", "Details")])
    buffer = io.BytesIO()
    wb.save(buffer)
    return buffer.getvalue()


def to_csv(rows: list[dict[str, Any]]) -> str:
    if not rows:
        return ""
    buffer = io.StringIO()
    writer = csv.DictWriter(buffer, fieldnames=list(rows[0].keys()), extrasaction="ignore")
    writer.writeheader()
    for row in rows:
        writer.writerow({k: (v if not isinstance(v, (list, dict)) else str(v)) for k, v in row.items()})
    return buffer.getvalue()
